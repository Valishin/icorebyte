<?php

namespace App\Mail\Chat;

use App\Models\ChatConversation;
use App\Models\ChatMessage;
use Illuminate\Mail\Mailable;
use Illuminate\Mail\Mailables\Content;
use Illuminate\Mail\Mailables\Envelope;
use Illuminate\Support\Facades\URL;

class ConversationNotificationMailable extends Mailable
{
    public string $resumeUrl;

    private static array $subjects = [
        'es' => 'Tienes un nuevo mensaje de iCOREBYTE',
        'ca' => 'Tens un nou missatge d\'iCOREBYTE',
        'en' => 'You have a new message from iCOREBYTE',
        'fr' => 'Vous avez un nouveau message d\'iCOREBYTE',
    ];

    /**
     * @param string $plainNonce One-time nonce (plain text) generated by the Job.
     *   The Job stores hash('sha256', $plainNonce) in the DB BEFORE calling Mail::send().
     *   The nonce travels in the signed URL — it is NOT the visitor token.
     */
    public function __construct(
        public readonly ChatConversation $conversation,
        public readonly ChatMessage $message,
        string $plainNonce,
    ) {
        $this->resumeUrl = URL::temporarySignedRoute(
            'chat.resume',
            now()->addDays(7),
            ['uuid' => (string) $conversation->uuid, 'nonce' => $plainNonce],
        );
    }

    public function envelope(): Envelope
    {
        $locale  = $this->conversation->locale ?? 'es';
        $subject = self::$subjects[$locale] ?? self::$subjects['es'];

        return new Envelope(subject: $subject);
    }

    public function content(): Content
    {
        return new Content(
            view: 'mail.chat.conversation-notification',
        );
    }
}
